esp_err_t specter_hx8394_init(esp_lcd_panel_io_handle_t panel_io) {
  if (!panel_io) {
    return ESP_ERR_INVALID_ARG;
  }
  for (size_t index = 0; index < ARRAY_SIZE(hx8394_init_commands); ++index) {
    const hx8394_init_command_t* item = &hx8394_init_commands[index];
    esp_err_t result = esp_lcd_panel_io_tx_param(
        panel_io, item->command, item->data_size ? item->data : NULL,
        item->data_size);
    if (ESP_OK != result) {
      return result;
    }
    if (item->delay_ms) {
      vTaskDelay(pdMS_TO_TICKS(item->delay_ms));
    }
  }
  return ESP_OK;
}
